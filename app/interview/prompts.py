"""面试 Agent 的提示词模板（M5 多 Agent 时会按角色拆分）"""

# 生成面试问题的提示词：{...} 是 format 占位符，JSON 中的花括号需双写转义
QUESTION_PROMPT = """你是「{position}」岗位的技术面试官，正在面试候选人 {candidate_name}。
已完成的问答：
{history_text}

请提出下一个面试问题：优先覆盖尚未考察过的知识点；若是追问则围绕刚才的回答深入。
只输出问题本身，不要编号、解释或其他任何内容。"""

# 评估回答的提示词：强制 JSON 输出，便于程序结构化处理
EVALUATE_PROMPT = """你是「{position}」岗位的技术面试官。请评估候选人对下面问题的回答。

题目：{question}
候选人回答：{answer}

严格按以下 JSON 格式输出，不要输出 JSON 之外的任何内容：
{{
  "score": <0-10 整数>,
  "comment": "<一两句话的评估意见>",
  "action": "<followup 或 next 或 finish>"
}}
判定规则：
- score < 5 或回答明显不完整 → action = followup
- 已考察 3 题以上且候选人无重大知识缺陷 → action = finish（面试时长有限，应及时收尾，不要无限追问）
- 其余情况 → action = next"""

# 面试总结提示词（M2 新增：LangGraph 图中 finish 分支的收尾节点使用）
SUMMARY_PROMPT = """你是「{position}」岗位的技术面试官，候选人 {candidate_name} 的面试已结束。
以下是全部问答记录：
{history_text}

请用 3-5 句话给出整体评价：先说突出优势，再指出短板，最后给出是否推荐的结论。
只输出评价正文，不要客套开场白。"""

# M3-b：带工具的出题提示词——告知模型可以查题库，并约定复用优先策略
# M4 起不再注入全量历史，改注入"记忆文本"（早期摘要 + 最近滑窗原文）
# M5 起接受规划官的 directive 定向出题（人设 system prompt 在 agents.py）
QUESTION_WITH_TOOLS_PROMPT = """你是「{position}」岗位的技术面试官，正在面试候选人 {candidate_name}。
考察规划（规划官指示，必须遵循）：
{directive}

历史面试记忆（更早的问答已压缩为摘要，最近几轮保留原文）：
{memory_text}

你可以调用工具 search_question_bank 查询题库中已有的题目：
- 查到合适的题目：直接原样采用其中一道
- 没有合适的：自己原创一道
只输出问题本身，不要编号、解释或其他任何内容。"""

# M4：记忆压缩提示词——把滑窗外的早期问答滚动合并进摘要
# 摘要的唯一评价标准：对"决定下一题问什么"有没有用
MEMORY_COMPRESS_PROMPT = """你是一场「{position}」面试的记录员。请把下面的新问答信息合并进已有摘要。

已有摘要：
{existing_summary}

新完成的问答：
{new_text}

要求：
- 保留对后续出题有用的信息：已考察过的知识点、得分与能力趋势、暴露的短板、值得追问的疑点
- 合并去重，按条目组织，总长度不超过 150 字
- 只输出摘要正文，不要任何解释或开场白"""

# M5：考察规划官的任务指令（角色人设 PLANNER_SYSTEM 在 agents.py）
PLANNER_PROMPT = """你负责规划「{position}」岗位面试的下一个考察方向。以下是目前为止的面试记忆：
{memory_text}

请决定下一个考察知识点：优先补齐尚未覆盖的方向；若最近回答暴露明显短板且值得再给一次机会，也可指定继续深入该知识点。
严格按以下 JSON 格式输出，不要输出 JSON 之外的任何内容：
{{
  "topic": "<下一个考察的知识点>",
  "guidance": "<给面试官的一句话出题指令，说明考察角度和深度>"
}}"""
